import assert from 'node:assert/strict';
const origin = process.argv[2];
assert.ok(origin, 'Supply an isolated gateway origin');
const login = await fetch(`${origin}/login`, { signal: AbortSignal.timeout(10000) });
assert.equal(login.status, 200);
const html = await login.text();
assert.ok(html.includes('Sign in to open your personal bucket.'));
assert.ok(html.includes('/drive-api/api/auth/google/login'));
assert.ok(html.includes('Continue with Google'));
const asset = html.match(/src="([^" ]*\/_next\/static\/[^" ]+\.js)"/);
assert.ok(asset, 'Login should reference a JavaScript bundle');
const js = await fetch(new URL(asset[1], origin), { signal: AbortSignal.timeout(10000) });
assert.equal(js.status, 200);
assert.ok(js.headers.get('content-type')?.includes('javascript'));
assert.ok((await js.text()).length > 100);
const proxy = await fetch(`${origin}/drive-api/api/health`, { signal: AbortSignal.timeout(10000) });
assert.equal(proxy.status, 200);
assert.equal(await proxy.text(), '/api/health|drive.sudarshanrajagopalan.one|https');
const unauthenticated = await fetch(`${origin}/drive-api/api/auth/me`, { signal: AbortSignal.timeout(10000) });
assert.equal(unauthenticated.status, 401);
console.log('PASS login content, auth URL, JS asset, proxy prefix/host/protocol, unauthenticated status');
console.log('Mock backend only: real authentication, uploads and WebSockets are not validated.');
